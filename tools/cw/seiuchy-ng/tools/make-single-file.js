#!/usr/bin/env node
/*
 * Builds a standalone seiuchy.html with the CSS, the scripts and the icon
 * inlined, so the trainer is one file that depends on nothing beside it.
 *
 * Why this exists: Android file managers hand the browser a content:// URI,
 * which addresses a single document and has no sibling directory, so a page
 * that pulls in seiuchy.css and data.js gets nothing.  Copying one file to a
 * phone and opening it is the simplest way to use the trainer, and it only
 * works if the file really is self-contained.
 *
 * The app itself still has no build step -- index.html and its siblings are the
 * source and work as they are.  This only produces an extra artefact for
 * carrying around; it is not part of the app and is not committed.
 *
 *   node tools/make-single-file.js [output.html]     default: seiuchy.html
 */
'use strict';

const fs = require('fs');
const path = require('path');
const { APP_DIR } = require('./lib');

const output = path.resolve(process.argv[2] || path.join(APP_DIR, 'seiuchy.html'));
const read = (file) => fs.readFileSync(path.join(APP_DIR, file), 'utf8');
const readBase64 = (file) => fs.readFileSync(path.join(APP_DIR, file)).toString('base64');

/* A closing tag inside inlined code would end the <script> element early. */
const escapeForScript = (code) => code.replace(/<\/(script)/gi, '<\\/$1');

let html = read('index.html');
const inlined = [];

/* Stylesheet -> <style> */
html = html.replace(/<link rel="stylesheet" href="([^"]+)">/g, (match, href) => {
  inlined.push(href);
  return '<style>\n' + read(href).trim() + '\n</style>';
});

/* Scripts -> inline, in the same order, which is what the app depends on. */
html = html.replace(/<script src="([^"]+)"><\/script>/g, (match, src) => {
  inlined.push(src);
  return '<script>\n' + escapeForScript(read(src).trim()) + '\n</script>';
});

/* The masthead icon -> a data URI, so the <img> tag and its styling survive. */
html = html.replace(/(<img src=")icon\.svg(")/,
  (match, before, after) => {
    inlined.push('icon.svg');
    return before + 'data:image/svg+xml;base64,' + readBase64('icon.svg') + after;
  });

/* Favicons -> data URIs.  The manifest and the service worker are dropped:
   neither can do anything without a server, and both would 404. */
html = html.replace(/<link rel="(icon|apple-touch-icon)"([^>]*)href="icon-192\.png"([^>]*)>/g,
  (match, rel, before, after) => {
    inlined.push('icon-192.png');
    return `<link rel="${rel}"${before}href="data:image/png;base64,${readBase64('icon-192.png')}"${after}>`;
  });
html = html.replace(/\s*<link rel="manifest"[^>]*>/g, '');

/* Leave a note in the file about where it came from. */
html = html.replace('<head>',
  '<head>\n<!-- Standalone build: CSS, scripts and icons inlined.\n' +
  '     Generated by tools/make-single-file.js -- edit the source files, not this. -->');

fs.writeFileSync(output, html);

/* Nothing may be left pointing outside the file. */
const leftovers = [...html.matchAll(/(?:src|href)="(?!data:|#|https?:)([^"]+)"/g)].map((m) => m[1]);

console.log(`\n  wrote ${output}  (${(Buffer.byteLength(html) / 1024).toFixed(0)} KB)`);
console.log('  inlined: ' + inlined.join(', '));
if (leftovers.length) {
  console.log('\n  WARNING: still references files beside it: ' + leftovers.join(', '));
  process.exit(1);
}
console.log('  no external references -- safe to copy on its own\n');
